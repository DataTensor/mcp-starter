// Helper to generate realistic candle bars
function generateCandles(basePrice: number, volatility: number, count: number = 40): Candle[] {
  const candles: Candle[] = [];
  const now = Date.now();
  const dayMs = 24 * 60 * 60 * 1000;
  let currentClose = basePrice * (1 - volatility * (count / 2) * 0.01);

  for (let i = 0; i < count; i++) {
    const timestamp = now - (count - i) * dayMs;
    const dateObj = new Date(timestamp);
    const time = `${dateObj.getMonth() + 1}/${dateObj.getDate()}`;

    // random daily movement
    const pctChange = (Math.random() - 0.48) * volatility * 0.05;
    const open = currentClose;
    currentClose = Math.max(0.01, open * (1 + pctChange));

    const wickUp = Math.random() * volatility * 0.03 * open;
    const wickDown = Math.random() * volatility * 0.03 * open;

    const high = Math.max(open, currentClose) + wickUp;
    const low = Math.min(open, currentClose) - wickDown;
    const volume = Math.floor((1000000 + Math.random() * 5000000) * (basePrice > 1000 ? 0.2 : 1.5));

    candles.push({
      time,
      timestamp,
      open: Number(open.toFixed(basePrice > 100 ? 2 : 4)),
      high: Number(high.toFixed(basePrice > 100 ? 2 : 4)),
      low: Number(Math.max(0.01, low).toFixed(basePrice > 100 ? 2 : 4)),
      close: Number(currentClose.toFixed(basePrice > 100 ? 2 : 4)),
      volume,
    });
  }

  // Ensure last candle close matches current basePrice
  const last = candles[candles.length - 1];
  last.close = basePrice;
  last.high = Math.max(last.high, basePrice);
  last.low = Math.min(last.low, basePrice);

  return candles;
}

function sparkFromCandles(candles: Candle[]): number[] {
  return candles.map((c) => c.close);
}

